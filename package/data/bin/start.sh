#!/bin/sh
# EE container entrypoint (overrides the EE-generated /bin/start.sh).
#
# WHY THIS EXISTS: on this firmware nothing acts on an Execution Unit's
# AutoStart flag at COLD BOOT — the container comes up and runs `zyeed -n <ee>`,
# but the EU's daemons are only launched by a live management trigger (the web-UI
# "Activate" click or an ACS session), so after a reboot the service stays down.
# The container + this start.sh DO run on every boot, so we launch our supervisor
# (/sbin/anondns.sh) directly here, then keep `zyeed -n anondns` as the EE's
# foreground anchor exactly as the stock script did. anondns.sh self-locks, so a
# later manual "Activate" won't double-start it.
#
# NOTE: regenerated by the EE only when the Execution Environment is (re)created;
# reinstalling the DU re-applies this file.
export PATH=/bin:/sbin:/usr/bin:/usr/sbin
export LD_LIBRARY_PATH=/lib:/usr/lib:/lib64
/sbin/anondns.sh >/dev/null 2>&1 &
exec zyeed -n anondns 2>&1
